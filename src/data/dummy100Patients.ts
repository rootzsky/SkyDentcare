export function compute100PatientsAnalytics(patients: DentalPatient100[] = dummy100Patients) {
  const total = patients.length;
  if (total === 0) return null;

  let totalDecay = 0;
  let totalMissing = 0;
  let totalFilled = 0;
  let totalDMFT = 0;
  let totalOHIS = 0;
  let totalPlaque = 0;

  const ageGroupsCount: Record<string, number> = {
    pediatrik: 0,
    remaja: 0,
    dewasa_muda: 0,
    dewasa: 0,
    lansia: 0
  };

  const diagnosisCount: Record<string, number> = {};
  const insuranceCount: Record<string, number> = {};
  const cityCount: Record<string, number> = {};
  const genderCount = { L: 0, P: 0 };
  const dmftCategoryCount: Record<string, number> = {
    'Sangat Rendah': 0,
    'Rendah': 0,
    'Sedang': 0,
    'Tinggi': 0,
    'Sangat Tinggi': 0
  };
  const ohisCategoryCount: Record<string, number> = {
    'Baik': 0,
    'Sedang': 0,
    'Buruk': 0
  };
  const periodontalCount: Record<string, number> = {
    'Sehat': 0,
    'Gingivitis Marginalis': 0,
    'Periodontitis Ringan': 0,
    'Periodontitis Kronis Sedang-Berat': 0
  };

  let activeCariesCount = 0;
  let impactionCount = 0;
  let edentulousCount = 0;

  patients.forEach(p => {
    totalDecay += p.dmft.decay;
    totalMissing += p.dmft.missing;
    totalFilled += p.dmft.filled;
    totalDMFT += p.dmft.total;
    totalOHIS += p.ohis.totalScore;
    totalPlaque += p.plaqueIndex;

    ageGroupsCount[p.ageGroup] = (ageGroupsCount[p.ageGroup] || 0) + 1;
    genderCount[p.gender] = (genderCount[p.gender] || 0) + 1;
    insuranceCount[p.insurance] = (insuranceCount[p.insurance] || 0) + 1;
    cityCount[p.city] = (cityCount[p.city] || 0) + 1;

    // Diagnose group simplification
    let diagGroup = 'Lainnya';
    if (p.primaryDiagnosis.toLowerCase().includes('karies') || p.primaryDiagnosis.toLowerCase().includes('caries')) {
      diagGroup = 'Karies Gigi';
      activeCariesCount++;
    } else if (p.primaryDiagnosis.toLowerCase().includes('pulpitis')) {
      diagGroup = 'Pulpitis / Endodontik';
      activeCariesCount++;
    } else if (p.primaryDiagnosis.toLowerCase().includes('periodontitis')) {
      diagGroup = 'Periodontitis';
    } else if (p.primaryDiagnosis.toLowerCase().includes('gingivitis')) {
      diagGroup = 'Gingivitis';
    } else if (p.primaryDiagnosis.toLowerCase().includes('impaksi')) {
      diagGroup = 'Impaksi M3 (Gigi Bungsu)';
      impactionCount++;
    } else if (p.primaryDiagnosis.toLowerCase().includes('edentulous') || p.primaryDiagnosis.toLowerCase().includes('kehilangan gigi') || p.primaryDiagnosis.toLowerCase().includes('gtsl')) {
      diagGroup = 'Kehilangan Gigi (Edentulous)';
      edentulousCount++;
    } else if (p.primaryDiagnosis.toLowerCase().includes('nekrosis')) {
      diagGroup = 'Nekrosis Pulpa';
    } else if (p.primaryDiagnosis.toLowerCase().includes('maloklusi') || p.primaryDiagnosis.toLowerCase().includes('crowding')) {
      diagGroup = 'Maloklusi & Ortodonti';
    }

    diagnosisCount[diagGroup] = (diagnosisCount[diagGroup] || 0) + 1;

    dmftCategoryCount[p.dmft.category] = (dmftCategoryCount[p.dmft.category] || 0) + 1;
    ohisCategoryCount[p.ohis.category] = (ohisCategoryCount[p.ohis.category] || 0) + 1;

    if (periodontalCount[p.periodontalStatus] !== undefined) {
      periodontalCount[p.periodontalStatus]++;
    } else {
      periodontalCount['Gingivitis Marginalis']++;
    }
  });

  return {
    totalPatients: total,
    averages: {
      dmft: Number((totalDMFT / total).toFixed(2)),
      decay: Number((totalDecay / total).toFixed(2)),
      missing: Number((totalMissing / total).toFixed(2)),
      filled: Number((totalFilled / total).toFixed(2)),
      ohis: Number((totalOHIS / total).toFixed(2)),
      plaqueIndex: Number((totalPlaque / total).toFixed(2))
    },
    activeCariesRate: Math.round((activeCariesCount / total) * 100),
    periodontalDiseaseRate: Math.round(((periodontalCount['Gingivitis Marginalis'] + periodontalCount['Periodontitis Ringan'] + periodontalCount['Periodontitis Kronis Sedang-Berat']) / total) * 100),
    impactionRate: Math.round((impactionCount / total) * 100),
    ageGroupsCount,
    genderCount,
    diagnosisCount,
    insuranceCount,
    cityCount,
    dmftCategoryCount,
    ohisCategoryCount,
    periodontalCount
  };
}

